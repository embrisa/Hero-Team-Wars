import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";
import { toJSONSchema } from "zod/v4";
import { objectFieldLookupSchema, objectFieldSearchSchema } from "../dist/schemas/tools.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const bytes = readFileSync(resolve(root, "map-engine/data/object-fields.json"));
const catalog = JSON.parse(bytes);
const digest = createHash("sha256").update(bytes).digest("hex").toUpperCase();
const lines = ["# Object field catalog (generated)", "", "Generated by `npm run generate:object-fields` in `mcp-server`. Do not edit this table manually.", "",
  "See [object-field-authoring.md](object-field-authoring.md) for authoring, preservation and validation rules.", "",
  `Catalog version: ${catalog.catalog_version}. Source file SHA-256: \`${digest}\`.`, "",
  `Metadata upstream commit: \`${catalog.upstream_commit}\`. Game version: ${catalog.game_version}.`, "",
  "All entries have static codec evidence; none imply runtime verification or universal patch compatibility.", "",
  "| Category | Field ID | Readable name | Type | Scope | Base restriction | Meaning |", "|---|---|---|---|---|---|---|"];
for (const f of catalog.fields) {
  const scope = f.scope === "level" ? `${f.repeat ? "level >= 1" : "level 0"}; pointer ${f.data_pointer}` : f.scope;
  lines.push(`| ${f.category} | \`${f.id}\` | \`${f.name}\` | ${f.type} | ${scope} | ${f.base_rawcodes.join(", ") || "category-wide"} | ${f.description} |`);
}
lines.push("", "## Enumerations and flags", "");
for (const f of catalog.fields.filter(f => f.values.length)) {
  lines.push(`- \`${f.name}\` [\`${f.id}\`]: ${f.values.map(v => `\`${v.name}\` = ${v.value}`).join(", ")}.`);
}
lines.push("", "## Pinned source evidence", "");
for (const [name, source] of Object.entries(catalog.sources)) lines.push(`- [${name}](${source.url}); SHA-256 \`${source.sha256}\`.`);
lines.push("", "Metadata facts are a reviewed subset of upstream test fixtures. Readable names/descriptions and hero-attachment policy are repository-maintained authoring choices. Refresh explicitly with `python scripts/sync-object-fields.py`, review the diff, rebuild, and regenerate this reference. Runtime never downloads metadata.", "");

const outputs = new Map([["docs/reference/object-fields.generated.md", lines.join("\n")]]);
for (const [name, schema] of [["lookup", objectFieldLookupSchema], ["search", objectFieldSearchSchema]]) {
  outputs.set(`contracts/schemas/object-field-${name}.schema.json`, JSON.stringify(toJSONSchema(schema), null, 2) + "\n");
}
for (const [path, content] of outputs) {
  const full = resolve(root, path);
  if (process.argv.includes("--check")) {
    if (readFileSync(full, "utf8").replaceAll("\r\n", "\n") !== content) throw new Error(`Stale generated contract/reference: ${path}`);
  } else writeFileSync(full, content);
}
console.log(`Object-field reference and ${outputs.size - 1} tool schemas ${process.argv.includes("--check") ? "verified" : "generated"}.`);
